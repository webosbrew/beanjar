// A genuine wired Xbox 360 controller's descriptors (045e:028e, bcdDevice 1.14), byte for byte,
// from a USB capture of the controller published by David Madison, "Understanding the Xbox 360
// Wired Controller's USB Data" (partsnotincluded.com, 2019): its device descriptor, its 153-byte
// configuration descriptor (four vendor-specific interfaces, each with its undocumented class
// descriptor 0x21 or 0x41) and its four strings. The serial number is the captured one.
//
// Interface 0 (ff/5d/01) is the one xpad binds: interrupt IN 0x81 (the input report, 4 ms) and
// interrupt OUT 0x01 (LED and rumble, 8 ms). Interface 1 (ff/5d/03) is the headset, interface 2
// (ff/5d/02) an IN endpoint no driver polls, interface 3 (ff/fd/13) the console's security method,
// with no endpoints.
#pragma once

#include <cstdint>

namespace virtpad::descriptors
{

// clang-format off
inline constexpr std::uint8_t device[] = {
    0x12, 0x01, 0x00, 0x02, 0xff, 0xff, 0xff, 0x08, 0x5e,
    0x04, 0x8e, 0x02, 0x14, 0x01, 0x01, 0x02, 0x03, 0x01,
};
// clang-format on

// clang-format off
inline constexpr std::uint8_t configuration[] = {
    // configuration: 153 bytes, 4 interfaces, value 1, bus-powered, remote wakeup, 500 mA
    0x09, 0x02, 0x99, 0x00, 0x04, 0x01, 0x00, 0xa0, 0xfa,
    // interface 0: ff/5d/01, 2 endpoints
    0x09, 0x04, 0x00, 0x00, 0x02, 0xff, 0x5d, 0x01, 0x00, 0x11, 0x21, 0x00, 0x01, 0x01, 0x25, 0x81,
    0x14, 0x00, 0x00, 0x00, 0x00, 0x13, 0x01, 0x08, 0x00, 0x00, 0x07, 0x05, 0x81, 0x03, 0x20, 0x00,
    0x04, 0x07, 0x05, 0x01, 0x03, 0x20, 0x00, 0x08,
    // interface 1: ff/5d/03, 4 endpoints (the headset)
    0x09, 0x04, 0x01, 0x00, 0x04, 0xff, 0x5d, 0x03, 0x00, 0x1b, 0x21, 0x00, 0x01, 0x01, 0x01, 0x82,
    0x40, 0x01, 0x02, 0x20, 0x16, 0x83, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x16, 0x03, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x07, 0x05, 0x82, 0x03, 0x20, 0x00, 0x02, 0x07, 0x05, 0x02, 0x03, 0x20,
    0x00, 0x04, 0x07, 0x05, 0x83, 0x03, 0x20, 0x00, 0x40, 0x07, 0x05, 0x03, 0x03, 0x20, 0x00, 0x10,
    // interface 2: ff/5d/02, 1 endpoint
    0x09, 0x04, 0x02, 0x00, 0x01, 0xff, 0x5d, 0x02, 0x00, 0x09, 0x21, 0x00, 0x01, 0x01, 0x22, 0x84,
    0x07, 0x00, 0x07, 0x05, 0x84, 0x03, 0x20, 0x00, 0x10,
    // interface 3: ff/fd/13, no endpoints, string 4
    0x09, 0x04, 0x03, 0x00, 0x00, 0xff, 0xfd, 0x13, 0x04, 0x06, 0x41, 0x00, 0x01, 0x01, 0x03,
};
// clang-format on

static_assert(sizeof configuration == 153);

// strings 1 to 4 (iManufacturer, iProduct, iSerialNumber, interface 3's iInterface), UTF-8
inline constexpr const char *strings[] = {
    "\xc2\xa9Microsoft Corporation",
    "Controller",
    "08FEC93",
    "Xbox Security Method 3, Version 1.00, \xc2\xa9 2005 Microsoft Corporation. All rights "
    "reserved.",
};
inline constexpr std::uint16_t LANGID = 0x0409; // string 0: US English

} // namespace virtpad::descriptors
